#!/usr/bin/env bash
#
# kharej-client.sh — set up the foreign side of the tunnel.
#
# The foreign server is Backpack's *client* role: it dials the Iran server and
# forwards the arriving traffic to the real service. Because the connection is
# always originated here, no packet leaves Iran towards this machine's address,
# and this machine needs no open inbound port of its own.
#
# Run this AFTER the Iran side — it needs that server's address and token.
#
# Usage:
#   sudo ./deploy/kharej-client.sh --server IP:PORT --token TOKEN [options]
#
# Options:
#   --server ADDR       Iran server address as IP:PORT (required)
#   --token TOKEN       token printed by iran-server.sh (required)
#   --transport NAME    must match the Iran side (default: wssmux)
#   --backup LIST       comma-separated spare addresses for the SAME server:
#                       a second IP, another port, or a CDN edge. The client
#                       fails over to these when the main address stops
#                       answering. e.g. "5.6.7.8:8443,edge.example.com:443"
#   --edge IP           connect to this CDN edge instead of the origin, so the
#                       Iran server's own address is never dialled directly.
#                       Needs wss/wssmux on a CDN-proxied port.
#   --load-balance      use every address at once instead of keeping the spares
#                       idle, so one throttled route slows only its own share
#   --pool N            connection pool size (default: 8)
#   --name NAME         tunnel name (default: main)
#   --no-tune           skip kernel tuning
#   -h, --help          this text
#
# Note: where traffic goes once it arrives here is NOT set on this side. The
# destination travels over the tunnel, taken from the Iran server's port
# mapping — "443=127.0.0.1:8080" there means users hitting :443 in Iran are
# forwarded to 127.0.0.1:8080 on this machine. Change the target with
# --ports on iran-server.sh, not here.

set -euo pipefail
# Resolve this file before changing directory, so --help can still read it.
SELF="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/$(basename "${BASH_SOURCE[0]}")"
cd "$(dirname "$SELF")"
source ./common.sh

usage() { sed -n '2,37p' "$SELF" | sed 's/^# \{0,1\}//'; }

SERVER="" TOKEN="" TRANSPORT="wssmux" BACKUP="" EDGE=""
LOADBAL=0 POOL=8 NAME="main" TUNE=1

while [[ $# -gt 0 ]]; do
  case "$1" in
    --server)       SERVER="${2:?--server needs a value}"; shift 2 ;;
    --token)        TOKEN="${2:?--token needs a value}"; shift 2 ;;
    --transport)    TRANSPORT="${2:?--transport needs a value}"; shift 2 ;;
    --backup)       BACKUP="${2:?--backup needs a value}"; shift 2 ;;
    --edge)         EDGE="${2:?--edge needs a value}"; shift 2 ;;
    --load-balance) LOADBAL=1; shift ;;
    --pool)         POOL="${2:?--pool needs a value}"; shift 2 ;;
    --name)         NAME="${2:?--name needs a value}"; shift 2 ;;
    --no-tune)      TUNE=0; shift ;;
    -h|--help)      usage; exit 0 ;;
    *)              die "unknown option: $1  (try --help)" ;;
  esac
done

require_root
[[ -n "$SERVER" ]] || die "--server is required (the Iran server, as IP:PORT)"
[[ -n "$TOKEN" ]]  || die "--token is required (printed by iran-server.sh)"
[[ "$SERVER" == *:* ]] || die "--server must include a port, e.g. 1.2.3.4:443"
validate_transport "$TRANSPORT"
[[ -n "$EDGE" ]] && warn_if_cdn_incompatible "$TRANSPORT"

install_backpack
[[ $TUNE -eq 1 ]] && tune_kernel

FALLBACK_TOML="$(toml_array "$BACKUP")"
EDGE_TOML=""
[[ -n "$EDGE" ]] && EDGE_TOML=$'\nedge_ip = "'"$EDGE"$'"'
LB_TOML="false"; [[ $LOADBAL -eq 1 ]] && LB_TOML="true"

# `remote_addr` being set is what marks this config as the client role.
write_config "$NAME" "# Foreign side (client role) — generated by paket-tunnel
# Dials the Iran server and forwards arriving traffic to the local service.

[client]
remote_addr = \"$SERVER\"
transport = \"$TRANSPORT\"
token = \"$TOKEN\"

# Spare addresses for the SAME server — a second IP, another port, or a CDN
# edge. When the live address stops answering the client moves to the next
# one on its own, which is what keeps the tunnel up after an IP gets filtered.
fallback_addrs = $FALLBACK_TOML
load_balance = $LB_TOML$EDGE_TOML

connection_pool = $POOL
aggressive_pool = true
retry_interval = 3
dial_timeout = 10
keepalive_period = 75
nodelay = true
log_level = \"info\"
preset = \"balanced\"
"

install_unit "$NAME"

cat <<EOF

$(printf '%s' "$C_GRN")Kharej client is up.$(printf '%s' "$C_OFF")

  tunnel name   $NAME
  transport     $TRANSPORT
  dialling      $SERVER${EDGE:+  (via CDN edge $EDGE)}
  spares        ${BACKUP:-none — see below}

Traffic arriving here goes wherever the Iran server's port mapping says —
"443=127.0.0.1:8080" there sends it to 127.0.0.1:8080 on this machine. Adjust
it with --ports on iran-server.sh.

$(if [[ -z "$BACKUP" ]]; then cat <<'HINT'
No spare addresses are configured. A single filtered IP will take this tunnel
down. Add a second address for the same server as soon as you have one:

  sudo ./deploy/kharej-client.sh ... --backup 5.6.7.8:8443,edge.example.com:443

HINT
fi)Verify the tunnel came up:

  journalctl -u backpack-$NAME -f

Then install the route watchdog on this machine:

  sudo ./watchdog/install.sh

And set up the DNS control channel before you need it, not after:

  sudo ./control-channel/setup-dnstt.sh server --domain t.example.com --forward 127.0.0.1:22
EOF
