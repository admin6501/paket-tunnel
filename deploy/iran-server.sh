#!/usr/bin/env bash
#
# iran-server.sh — set up the Iran side of the tunnel.
#
# The Iran server is Backpack's *server* role: it binds the ports that end users
# connect to, and waits for the kharej side to dial in. It never originates a
# connection towards the filtered foreign address, which is the whole point of
# running the tunnel in this direction.
#
# Run this FIRST — the kharej side needs the address and token printed here.
#
# Usage:
#   sudo ./deploy/iran-server.sh --ports 443,8443 [--transport wssmux] [options]
#
# Options:
#   --ports LIST        ports exposed to users. "443" or "443=127.0.0.1:8080"
#                       or a range "8000-8100". Comma-separated. (required)
#   --transport NAME    tcp|tcpmux|stealth|ws|wss|wsmux|wssmux|udp|kcp
#                       (default: wssmux)
#   --bind ADDR         listen address for the tunnel itself (default: 0.0.0.0:443)
#   --token TOKEN       reuse an existing token instead of generating one
#   --name NAME         tunnel name, one systemd unit per name (default: main)
#   --domain DOMAIN     request a Let's Encrypt certificate for this domain
#                       instead of the self-signed one (wss/wssmux only).
#                       Must already resolve to this server.
#   --email ADDR        ACME registration address (used with --domain)
#   --no-tune           skip kernel tuning
#   -h, --help          this text

set -euo pipefail
# Resolve this file before changing directory, so --help can still read it.
SELF="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/$(basename "${BASH_SOURCE[0]}")"
cd "$(dirname "$SELF")"
source ./common.sh

usage() { sed -n '2,28p' "$SELF" | sed 's/^# \{0,1\}//'; }

PORTS="" TRANSPORT="wssmux" BIND="0.0.0.0:443" TOKEN="" NAME="main"
DOMAIN="" EMAIL="" TUNE=1

while [[ $# -gt 0 ]]; do
  case "$1" in
    --ports)     PORTS="${2:?--ports needs a value}"; shift 2 ;;
    --transport) TRANSPORT="${2:?--transport needs a value}"; shift 2 ;;
    --bind)      BIND="${2:?--bind needs a value}"; shift 2 ;;
    --token)     TOKEN="${2:?--token needs a value}"; shift 2 ;;
    --name)      NAME="${2:?--name needs a value}"; shift 2 ;;
    --domain)    DOMAIN="${2:?--domain needs a value}"; shift 2 ;;
    --email)     EMAIL="${2:?--email needs a value}"; shift 2 ;;
    --no-tune)   TUNE=0; shift ;;
    -h|--help)   usage; exit 0 ;;
    *)           die "unknown option: $1  (try --help)" ;;
  esac
done

require_root
[[ -n "$PORTS" ]] || die "--ports is required (e.g. --ports 443,8443)"
validate_transport "$TRANSPORT"

if [[ -n "$DOMAIN" ]]; then
  case "$TRANSPORT" in
    wss|wssmux) : ;;
    *) die "--domain only applies to wss/wssmux (got '$TRANSPORT')" ;;
  esac
  [[ -n "$EMAIL" ]] || die "--domain also needs --email for ACME registration"
fi

[[ -n "$TOKEN" ]] || TOKEN="$(generate_token)"

install_backpack
[[ $TUNE -eq 1 ]] && tune_kernel

PORTS_TOML="$(toml_array "$PORTS")"
ACME_TOML=""
if [[ -n "$DOMAIN" ]]; then
  ACME_TOML=$'\nacme_domain = "'"$DOMAIN"$'"\nacme_email = "'"$EMAIL"$'"'
fi

# `bind_addr` being set is what marks this config as the server role — the
# engine picks its role from which of bind_addr/remote_addr is present.
write_config "$NAME" "# Iran side (server role) — generated by paket-tunnel
# Users connect to the ports below; the kharej client dials in to bind_addr.

[server]
bind_addr = \"$BIND\"
transport = \"$TRANSPORT\"
token = \"$TOKEN\"
ports = $PORTS_TOML

# A generous keepalive keeps the control channel alive across the short
# stalls that are normal on this path, instead of tearing the tunnel down.
keepalive_period = 75
heartbeat = 40
channel_size = 2048
nodelay = true
accept_udp = false
log_level = \"info\"
preset = \"balanced\"$ACME_TOML
"

install_unit "$NAME"

PUBIP="$(curl -fsS --max-time 5 https://api.ipify.org 2>/dev/null || echo '<this-server-ip>')"
BINDPORT="${BIND##*:}"

cat <<EOF

$(printf '%s' "$C_GRN")Iran server is up.$(printf '%s' "$C_OFF")

  tunnel name   $NAME
  transport     $TRANSPORT
  listening     $BIND
  user ports    $PORTS

  $(printf '%s' "$C_YLW")TOKEN  $TOKEN$(printf '%s' "$C_OFF")

Keep that token — the kharej side needs it and it is not recoverable from
anywhere but $BACKPACK_CONF_DIR/$NAME.toml.

Next, on the foreign server:

  sudo ./deploy/kharej-client.sh \\
    --server $PUBIP:$BINDPORT \\
    --token $TOKEN \\
    --transport $TRANSPORT

Status:  systemctl status backpack-$NAME
Logs:    journalctl -u backpack-$NAME -f
EOF
